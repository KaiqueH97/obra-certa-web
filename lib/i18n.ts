export function translateAuthMessage(locale: Locale, message: string): { text: string; lang: Locale } {
  // Mensagens ainda não catalogadas preservam o idioma original explicitamente.
  const translated = locale === "en" && Object.hasOwn(authMessages, message) ? authMessages[message] : undefined;
  return { text: translated ?? message, lang: translated ? "en" : "pt-BR" };
}

// Erros da simulação pública: traduz a apresentação sem alterar as regras de cálculo.
export function translateAreaMessage(locale: Locale, message: string): { text: string; lang: Locale } {
  if (locale === "en") {
    const messages: Record<string, string> = {
      "Adicione pelo menos uma área.": "Add at least one area.",
      "A área ultrapassa o intervalo calculável. Confira as medidas.": "The area exceeds the supported range. Check your measurements.",
      "A área total deve ser de pelo menos 0,01 m².": "The total area must be at least 0.01 m².",
    };
    if (Object.hasOwn(messages, message)) return { text: messages[message], lang: "en" };
    const invalid = /^Área (\d+): informe altura e largura maiores que zero, como 3,50 ou 3\.50, sem unidades ou separador de milhar\.$/.exec(message);
    if (invalid) return { text: `Area ${invalid[1]}: enter height and width greater than zero, such as 3.50 or 3,50, without units or thousands separators.`, lang: "en" };
  }
  return { text: message, lang: "pt-BR" };
}

export function formatNumber(locale: Locale, value: number, decimals: number): string {
  return new Intl.NumberFormat(locale === "en" ? "en-US" : "pt-BR", {
    minimumFractionDigits: decimals, maximumFractionDigits: decimals,
  }).format(value);
}
