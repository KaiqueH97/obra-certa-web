export type PrivateMessageKey = keyof typeof english;
type Values = Record<string, string | number>;

export function privateText(locale: Locale, key: PrivateMessageKey, values: Values = {}): string {
  const template = locale === "en" ? english[key] : key;
  // Substituição única: nomes com chaves, cifrões ou HTML continuam texto literal.
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match);
}

export function privateMessage(locale: Locale, message: string): { text: string; lang: Locale } {
  if (Object.hasOwn(english, message)) {
    return { text: privateText(locale, message as PrivateMessageKey), lang: locale };
  }
  return { text: message, lang: "pt-BR" };
}

export function formatBRL(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale === "en" ? "en-US" : "pt-BR", {
    style: "currency", currency: "BRL",
  }).format(value);
}
